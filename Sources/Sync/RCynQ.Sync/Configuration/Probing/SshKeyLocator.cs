using RCynQ.Core.Config;

namespace RCynQ.Sync.Configuration.Probing;

/// <summary>
/// Finds the SSH key of a node. Keys live in the node data directory, not in the user profile.
/// </summary>
public static class SshKeyLocator
{
    /// <summary>
    /// The file name of the key RCynQ generates.
    /// </summary>
    public const string DefaultKeyName = "rcynq_ed25519";

    /// <summary>
    /// Gets the private key path RCynQ generates when no identity file is configured.
    /// </summary>
    /// <param name="sshKeysDirectory">The SSH key directory of the node (<c>data/keys/ssh</c>).</param>
    /// <returns>The path.</returns>
    public static string DefaultPrivateKeyPath(string sshKeysDirectory)
        => Path.Combine(sshKeysDirectory, DefaultKeyName);

    /// <summary>
    /// Gets the public key files to look at: the configured identity, then the key generated by RCynQ.
    /// </summary>
    /// <param name="options">The SSH client options.</param>
    /// <param name="sshKeysDirectory">The SSH key directory of the node.</param>
    /// <returns>The candidate paths.</returns>
    public static IReadOnlyList<string> CandidatePublicKeyPaths(SshClientOptions options, string sshKeysDirectory)
    {
        ArgumentNullException.ThrowIfNull(options);
        var candidates = new List<string>();
        if (!string.IsNullOrWhiteSpace(options.IdentityFile))
        {
            candidates.Add(options.IdentityFile.Trim() + ".pub");
        }

        candidates.Add(DefaultPrivateKeyPath(sshKeysDirectory) + ".pub");
        return candidates.Distinct(StringComparer.Ordinal).ToArray();
    }
}
