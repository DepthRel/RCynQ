using RCynQ.Core.Validation;

namespace RCynQ.Core.Config;

/// <summary>
/// Resolved local application data paths of a node.
/// </summary>
/// <remarks>
/// All data and keys stay on the node. Patch payloads and bundles are stored as files, metadata in SQLite.
/// </remarks>
public sealed record AppDataPaths
{
    /// <summary>
    /// Initializes a new instance of the <see cref="AppDataPaths"/> record.
    /// </summary>
    /// <param name="root">The root application data directory.</param>
    /// <param name="databasePath">The full path of the SQLite database file.</param>
    /// <param name="patchesDirectory">The directory that stores patch payloads and bundles.</param>
    /// <param name="backupsDirectory">The directory that stores conflict backups.</param>
    /// <param name="keysDirectory">The directory that stores cryptographic keys.</param>
    /// <param name="logsDirectory">The directory that stores log files.</param>
    /// <param name="snapshotsDirectory">The directory that stores the sync base snapshot of the working tree.</param>
    /// <exception cref="ArgumentNullException">An argument is <see langword="null"/>.</exception>
    /// <exception cref="ArgumentException">An argument is blank.</exception>
    public AppDataPaths(
        string root,
        string databasePath,
        string patchesDirectory,
        string backupsDirectory,
        string keysDirectory,
        string logsDirectory,
        string snapshotsDirectory)
    {
        Root = Guard.NotBlank(root, nameof(root));
        DatabasePath = Guard.NotBlank(databasePath, nameof(databasePath));
        PatchesDirectory = Guard.NotBlank(patchesDirectory, nameof(patchesDirectory));
        BackupsDirectory = Guard.NotBlank(backupsDirectory, nameof(backupsDirectory));
        KeysDirectory = Guard.NotBlank(keysDirectory, nameof(keysDirectory));
        LogsDirectory = Guard.NotBlank(logsDirectory, nameof(logsDirectory));
        SnapshotsDirectory = Guard.NotBlank(snapshotsDirectory, nameof(snapshotsDirectory));
    }

    /// <summary>
    /// Gets the root application data directory.
    /// </summary>
    public string Root { get; }

    /// <summary>
    /// Gets the full path of the SQLite database file.
    /// </summary>
    public string DatabasePath { get; }

    /// <summary>
    /// Gets the directory that stores patch payloads and bundles.
    /// </summary>
    public string PatchesDirectory { get; }

    /// <summary>
    /// Gets the directory that stores conflict backups.
    /// </summary>
    public string BackupsDirectory { get; }

    /// <summary>
    /// Gets the directory that stores cryptographic keys.
    /// </summary>
    public string KeysDirectory { get; }

    /// <summary>
    /// Gets the directory that stores log files.
    /// </summary>
    public string LogsDirectory { get; }

    /// <summary>
    /// Gets the directory that stores the sync base snapshot.
    /// </summary>
    public string SnapshotsDirectory { get; }

    /// <summary>
    /// Gets the directory holding the shadow copy of the last synchronized working tree state.
    /// </summary>
    public string SyncBaseDirectory => Path.Combine(SnapshotsDirectory, "base");

    /// <summary>
    /// Gets the path of the file with the local management API token used by the UI and CLI.
    /// </summary>
    public string ApiTokenPath => Path.Combine(KeysDirectory, "api.token");

    /// <summary>
    /// Gets the directory of the node SSH key generated by RCynQ.
    /// </summary>
    public string SshKeysDirectory => Path.Combine(KeysDirectory, "ssh");

    /// <summary>
    /// Gets the <c>known_hosts</c> file used by the SSH connections of RCynQ instead of the one in the user profile.
    /// </summary>
    public string KnownHostsPath => Path.Combine(KeysDirectory, "known_hosts");

    /// <summary>
    /// Gets the directory holding the node's TLS certificate for the direct endpoint.
    /// </summary>
    public string TlsDirectory => Path.Combine(KeysDirectory, "tls");

    /// <summary>
    /// Gets the directory for temporary files (diff staging, patch files handed to Git).
    /// </summary>
    public string TempDirectory => Path.Combine(Root, "tmp");

    /// <summary>
    /// Gets the SQLite connection string for <see cref="DatabasePath"/>.
    /// </summary>
    public string ConnectionString => $"Data Source={DatabasePath}";

    /// <summary>
    /// Creates the path set with the standard layout below the given root.
    /// </summary>
    /// <param name="root">The root directory.</param>
    /// <returns>The path set.</returns>
    /// <exception cref="ArgumentException"><paramref name="root"/> is blank.</exception>
    public static AppDataPaths FromRoot(string root)
    {
        var fullRoot = Path.GetFullPath(Guard.NotBlank(root, nameof(root)));
        return new AppDataPaths(
            fullRoot,
            Path.Combine(fullRoot, "rcynq.db"),
            Path.Combine(fullRoot, "patches"),
            Path.Combine(fullRoot, "backups"),
            Path.Combine(fullRoot, "keys"),
            Path.Combine(fullRoot, "logs"),
            Path.Combine(fullRoot, "snapshots"));
    }
}
